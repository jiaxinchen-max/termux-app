#!/usr/bin/env python3
"""Build deterministic, independent theme archives and the shared component catalog.

Run from any directory. --check checks every generated byte without rewriting it.
"""
import argparse
import gzip
import hashlib
import io
import json
import shlex
from pathlib import Path
import tarfile

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'termux-ui/src/main/assets/local-games'
BUNDLES = ROOT / 'distribution/hyprland-themes/build'
JAVA = ROOT / 'termux-ui/src/main/java/com/termux/ui/desktop/domain/HyprlandComponents.java'
COMPONENT_RELEASE = 'hyprland-components-20261113-r1'
COMPONENT_BASE_URL = 'https://github.com/jiaxinchen-max/termux-app-packages/releases/download/' + COMPONENT_RELEASE
COMMON_FILES = ['bin/python3', 'bin/dbus-daemon', 'bin/swaybg', 'bin/dbus-send',
                'lib/xfce4/notifyd/xfce4-notifyd']
COMMON_PACKAGES = ['python', 'dbus', 'pulseaudio', 'swaybg', 'xfce4-notifyd', 'gtk-layer-shell',
                   'adwaita-icon-theme', 'xfce4-terminal']
THEMES = {
    'classic-r7': {'label': 'Classic · r7', 'delivery_revision': 'r7',
                   'files': ['bin/xfce4-panel', 'bin/xfconf-query', 'lib/xfce4/panel/plugins/libgenmon.so'],
                   'packages': ['xfce4-panel', 'xfce4-genmon-plugin']},
    'm3ww-v1': {'label': 'm3ww · v1 (r8)', 'delivery_revision': 'r8',
                'files': ['bin/eww', 'bin/foot', 'bin/fish', 'bin/starship', 'bin/fc-cache'],
                'packages': ['eww', 'foot', 'fish', 'starship', 'fontconfig-utils', 'pygobject']},
}


def sha(data):
    return hashlib.sha256(data).hexdigest()


def canonical(value):
    return (json.dumps(value, ensure_ascii=False, sort_keys=True, indent=2) + '\n').encode()


def archive(theme_id):
    source = ROOT / 'distribution/hyprland-themes' / theme_id
    files = {str(p.relative_to(source)): p.read_bytes() for p in sorted(source.rglob('*')) if p.is_file()}
    manifest = canonical({'schema': 1, 'id': theme_id, 'runtime_ids': ['0.57.0-r7'],
                          'files': {name: sha(data) for name, data in files.items()}})
    files['manifest.json'] = manifest
    output = io.BytesIO()
    with gzip.GzipFile(fileobj=output, mode='wb', filename='', mtime=0, compresslevel=9) as gz:
        with tarfile.open(fileobj=gz, mode='w', format=tarfile.USTAR_FORMAT) as tar:
            for name, data in sorted(files.items()):
                info = tarfile.TarInfo(name)
                info.size = len(data); info.mode = 0o644; info.mtime = 0
                tar.addfile(info, io.BytesIO(data))
    return output.getvalue(), sha(manifest), list(files)


def j(value):
    return json.dumps(value, ensure_ascii=True)


def java(catalog):
    runtime = catalog['runtimes']['0.57.0-r7']
    out = '''package com.termux.ui.desktop.domain;

/** Generated by tools/build-hyprland-themes.py; edit the catalog builder, then regenerate. */
public final class HyprlandComponents {
    public static final String RUNTIME_ID = "0.57.0-r7";
    public static final String CLASSIC = "classic-r7";
    public static final String DEFAULT_THEME = "m3ww-v1";
'''
    out += '    public static final String RUNTIME_MANIFEST = ' + j(runtime['manifest_sha256']) + ';\n'
    out += '    public static final String RELEASE = ' + j(runtime['release']) + ';\n'
    out += '''    private HyprlandComponents() { }
    public static void requireSupported(String runtime, String theme) {
        if (!RUNTIME_ID.equals(runtime) || !(CLASSIC.equals(theme) || DEFAULT_THEME.equals(theme)))
            throw new IllegalArgumentException("unsupported_hyprland_components");
    }
    public static String themeLabel(String theme) {
        requireSupported(RUNTIME_ID, theme);
        return CLASSIC.equals(theme) ? "Classic · r7" : "m3ww · v1 (r8)";
    }
    public static String[] themes() { return new String[]{CLASSIC, DEFAULT_THEME}; }
    public static String themeManifest(String theme) {
        requireSupported(RUNTIME_ID, theme);
'''
    a, b = (catalog['themes'][t]['manifest_sha256'] for t in ['classic-r7', 'm3ww-v1'])
    out += '        return CLASSIC.equals(theme) ? ' + j(a) + ' : ' + j(b) + ';\n    }\n'
    out += '''    public static String[] requiredFiles(String theme) {
        requireSupported(RUNTIME_ID, theme);
        return CLASSIC.equals(theme)
'''
    for i, t in enumerate(['classic-r7', 'm3ww-v1']):
        out += ('            ? ' if i == 0 else '            : ') + 'new String[]{' + ', '.join(j(f) for f in COMMON_FILES + THEMES[t]['files']) + '}' + ('\n' if i == 0 else ';\n')
    out += '    }\n'
    out += '    public static String[] resourceFiles(String theme) {\n        requireSupported(RUNTIME_ID, theme);\n        return CLASSIC.equals(theme)\n'
    for i, t in enumerate(['classic-r7', 'm3ww-v1']):
        out += ('            ? ' if i == 0 else '            : ') + 'new String[]{' + ', '.join(j(f) for f in catalog['themes'][t]['resource_files']) + '}' + ('\n' if i == 0 else ';\n')
    out += '    }\n}\n'
    return out.encode()


def shell(catalog):
    runtime = catalog['runtimes']['0.57.0-r7']
    out = '# Generated by tools/build-hyprland-themes.py. Do not edit.\n'
    out += 'hyprland_resolve_components() {\n'
    out += '    [ "${DESKTOP_HYPRLAND_RUNTIME_ID:-}" = 0.57.0-r7 ] || return 64\n'
    for key, field in [('HYPRLAND_RELEASE','release'), ('HYPRLAND_ASSET','asset'),
                       ('HYPRLAND_BASE_URL','base_url'), ('HYPRLAND_ARCHIVE_SHA256','archive_sha256')]:
        out += '    ' + key + '=' + shlex.quote(runtime[field]) + '\n'
    out += '    case "${DESKTOP_HYPRLAND_THEME_ID:-}" in\n'
    for theme_id, entry in catalog['themes'].items():
        out += '        ' + theme_id + ')\n'
        out += '            HYPRLAND_SUPPORT=' + shlex.quote(' '.join(entry['packages'])) + ' ;;\n'
    out += '        *) return 64 ;;\n    esac\n}\n'
    return out.encode()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    catalog = {'schema': 1, 'runtimes': {'0.57.0-r7': {
        'release': 'hyprland-android-0.57.0-70ec30e7-r7',
        'asset': 'hyprland-android-runtime-aarch64-0.57.0-r7.tar.gz',
        'base_url': 'https://github.com/jiaxinchen-max/termux-app-packages/releases/download/hyprland-android-0.57.0-70ec30e7-r7',
        'archive_sha256': '2fd3bd98104d7b411c9760efb2ad3270e950a1be4a146fa089b19a6fea169b10',
        'manifest_sha256': '6024fd61a4923031ce9d7c4d35c1d545e75cbff16fe1ae9ab8aab86a0167f948',
        'architecture': 'aarch64',
        'size': 58892089,
        'required_files': ['bin/Hyprland', 'bin/hyprctl', 'bin/Xwayland',
                           'lib/hyprland/android/libhyprland-system-gl.so', 'lib/hyprland/android/libvndksupport.so'],
    }}, 'themes': {}}
    outputs = {}
    for theme_id, entry in THEMES.items():
        data, manifest_sha, files = archive(theme_id)
        asset = 'hyprland-theme-' + theme_id + '.tgz'
        outputs[BUNDLES / asset] = data
        catalog['themes'][theme_id] = dict(entry, asset=asset, source='release',
            release=COMPONENT_RELEASE, url=COMPONENT_BASE_URL + '/' + asset, size=len(data),
            runtime_ids=['0.57.0-r7'], archive_sha256=sha(data), manifest_sha256=manifest_sha,
            required_files=COMMON_FILES + entry['files'], packages=COMMON_PACKAGES + entry['packages'],
            resource_files=sorted(files))
    outputs[ASSETS / 'hyprland-components.json'] = canonical(catalog)
    outputs[JAVA] = java(catalog)
    outputs[ASSETS / 'hyprland-components.sh'] = shell(catalog)
    for path, data in outputs.items():
        if args.check:
            if not path.is_file() or path.read_bytes() != data:
                raise SystemExit('Generated file differs: ' + str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True); path.write_bytes(data)
        print(('Checked ' if args.check else 'Wrote ') + str(path.relative_to(ROOT)))


if __name__ == '__main__':
    main()
